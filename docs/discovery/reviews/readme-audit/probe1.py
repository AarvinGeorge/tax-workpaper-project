import json, sys, re, collections
p = json.load(open(sys.argv[1]))
print("TOP KEYS:", list(p.keys()))
print("\n== firm.starter_standards ==")
print(json.dumps(p['firm']['starter_standards'], indent=1))
print("\n== firm keys ==", list(p['firm'].keys()))
print("firm_identity keys:", list(p['firm']['firm_identity'].keys()))
print("deadlines:", json.dumps(p['firm']['deadlines'], indent=1))
print("budget_hours:", p['firm']['budget_hours'])
print("assignment_at_start:", p['firm']['assignment_at_start'])
print("client_users:", p['firm']['client_users'])
print("\n== engine_reference ==")
er = p['engine_reference']
print("keys:", list(er.keys()))
print("parameters keys (%d):" % len(er['parameters']), list(er['parameters'].keys()))
print("rules (%d):" % len(er['rules']))
for k, v in list(er['rules'].items())[:8]: print(" ", k, ":", v[:100])
print("\n== return_versions ==")
for rv in p['return_versions']:
    print(rv['version'], rv['computed_at'], rv['trigger'][:80])
    print("  keys:", list(rv.keys()))
    print("  docs_used:", len(rv['documents_used']), "superseded:", rv['documents_superseded'])
    print("  summary:", json.dumps(rv['summary']))
    print("  tax_effect_rates:", json.dumps(rv['tax_effect_rates']))
    print("  carryovers_out:", json.dumps(rv['carryovers_out']))
    print("  assets n:", len(rv['assets']), "asset keys:", list(rv['assets'][0].keys()) if rv['assets'] else None)
    print("  diagnostics:", [(d['code'], d['severity']) for d in rv['diagnostics']])
    print("  changes_from_previous n:", len(rv['changes_from_previous']), "sample:", rv['changes_from_previous'][:2])
    print("  lines n:", len(rv['lines']), "line keys:", list(rv['lines'][0].keys()))
print("\n== what_if ==")
wi = p['what_if']
print("keys:", list(wi.keys()))
for a in wi['alternatives']:
    print(" ", a['id'], "| base", a['base_version'], "| choices", a['choices'], "| fed", a['federal'], "| ca", a['california'], "| changed_lines n", len(a['changed_lines']))
print("extension:", json.dumps(wi['extension'], indent=1))
print("\n== planning_reference_2026 ==", json.dumps(p['planning_reference_2026'], indent=1)[:1500])
print("\n== post_filing_rates ==", json.dumps(p['post_filing_rates'], indent=1))
print("\n== fx_rates ==", json.dumps(p['fx_rates']))
